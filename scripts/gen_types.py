"""Generate TypeScript types from backend/contracts.py (the single source of truth).

    uv run python scripts/gen_types.py --stdout
    uv run python scripts/gen_types.py --out app/types/contracts.ts     # P1 runs this

No third-party converter: walks each model's JSON schema and writes interfaces.
Models the phone sends (SessionCreate, LiveStart, ...) come out with optional fields
where the contract has a default; everything the server sends has every field required,
because the server always sends them all.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, get_args

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backend import contracts  # noqa: E402

DEFAULT_OUT = ROOT / "app" / "types" / "contracts.ts"
# Sent by the phone: defaults may be left out.
INPUT_MODELS = {"SessionCreate", "LiveStart", "LiveBargeIn", "LiveStop"}

LIVE_CLIENT = ["LiveStart", "LiveBargeIn", "LiveStop"]
LIVE_SERVER = ["LivePartial", "LiveFinal", "LiveResponse", "LiveTtsStart", "LiveTtsEnd", "LiveError"]


def _lit(value: Any) -> str:
    return json.dumps(value)


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return _lit(schema["const"])
    if "enum" in schema:
        return " | ".join(_lit(v) for v in schema["enum"])
    if "anyOf" in schema or "oneOf" in schema:
        parts = [ts_type(s) for s in schema.get("anyOf", schema.get("oneOf", []))]
        seen: list[str] = []
        for p in parts:
            if p not in seen:
                seen.append(p)
        return " | ".join(seen)
    t = schema.get("type")
    if isinstance(t, list):
        return " | ".join(ts_type({**schema, "type": x}) for x in t)
    if t == "string":
        return "string"
    if t in ("number", "integer"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        inner = ts_type(schema.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        return "Record<string, unknown>"
    return "unknown"


def interface(model: type) -> str:
    is_input = model.__name__ in INPUT_MODELS
    schema = model.model_json_schema(mode="validation" if is_input else "serialization")
    if is_input:
        # defaults may be omitted by the phone, but `type` tells the server which message it is
        required = set(schema.get("required", [])) | ({"type"} & set(schema.get("properties", {})))
    else:
        required = set(schema.get("properties", {}))  # the server always sends every field
    lines = [f"export interface {model.__name__} {{"]
    for name, prop in schema.get("properties", {}).items():
        mark = "" if name in required else "?"
        lines.append(f"  {name}{mark}: {ts_type(prop)};")
    lines.append("}")
    return "\n".join(lines)


def generate() -> str:
    names = [m.__name__ for m in contracts.EXPORTED_MODELS]
    out = [
        "// GENERATED by scripts/gen_types.py from backend/contracts.py. Do not edit by hand.",
        "// Boxes are normalised 0-1 from the top-left of the frame that was sent.",
        "",
        f"export type Phase = {' | '.join(_lit(v) for v in get_args(contracts.Phase))};",
        f"export type UserIntent = {' | '.join(_lit(v) for v in get_args(contracts.UserIntent))};",
        "",
    ]
    for model in contracts.EXPORTED_MODELS:
        out.append(interface(model))
        out.append("")
    assert all(n in names for n in LIVE_CLIENT + LIVE_SERVER)
    out.append(f"export type LiveClientMessage = {' | '.join(LIVE_CLIENT)};")
    out.append(f"export type LiveServerMessage = {' | '.join(LIVE_SERVER)};")
    out.append("")
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT, help=f"output path (default {DEFAULT_OUT.relative_to(ROOT)})")
    ap.add_argument("--stdout", action="store_true", help="print instead of writing a file")
    args = ap.parse_args()
    text = generate()
    if args.stdout:
        sys.stdout.write(text)
        return
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
